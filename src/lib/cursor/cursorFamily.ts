// The editor's cursor family as ONE parametric drawing (2026-10-21, owner note
// fbmvignyzogt73). Every state — the resting crosshair, the hover dot, the
// pressed contraction, the four resize axes, the rotate arcs, move and
// move-copy — is generated from the same template: same hotspot, same arm
// geometry, same stroke and halo. That registration is what makes a state
// change read as one mark changing form (hover a bottom handle: the two
// horizontal arms vanish and two arrowheads appear at the vertical arms' tips;
// nothing else moves) instead of three unrelated OS drawings per gesture.
//
// Pure: strings in, strings out. `styles/cursors.css` carries the DEFAULT
// family as static literals (first paint, before any JS) regenerated by
// scripts/gen-cursors.mjs from this module; `cursor/cursorTheme.ts` writes the
// same variables on :root when the user's Settings differ from the defaults.
// Hardware cursors stay hardware (`cursor: url()`): a DOM "software cursor"
// would trail the pointer by a frame, so the morph is geometric, never tweened.

export type CursorCentre = "none" | "dot" | "ring";
export type CursorResizeStyle = "crosshair" | "system";

export interface CursorParams {
  /** Mark size in CSS px (square); the hotspot is its centre. */
  size: number;
  /** Core (crosshair) stroke width in px. */
  stroke: number;
  /** Core stroke colour (6-digit hex) over LIGHT backgrounds (a figure's paper). */
  coreColor: string;
  /** Core stroke colour over DARK backgrounds (the app chrome, the canvas, dark
   *  paper, dark fills). Equal to `coreColor` when the cursor does not adapt. */
  coreColorDark: string;
  /** The halo drawn under the core so the mark reads on any background: its
   *  stroke width in px (0 = no halo), colour and opacity. */
  haloWidth: number;
  haloColor: string;
  haloOpacity: number;
  /** The accent dot (hover / press / rotate centre) and the move-copy badge. */
  dotColor: string;
  /** Centre gap radius in px — the pointed-at pixel is never covered. 0 = a continuous cross. */
  gap: number;
  /** What sits in the gap at REST (hover always adds the dot when `hoverDot`). */
  centre: CursorCentre;
  /** Hovering something selectable adds the accent dot. */
  hoverDot: boolean;
  /** A press contracts the arms. */
  pressContract: boolean;
  /** Resize/rotate/move states: drawn in the family, or the OS cursors. */
  resizeStyle: CursorResizeStyle;
}

