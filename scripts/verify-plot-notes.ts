import { createRequire } from "node:module";
import { mkdtemp, mkdir, writeFile, readFile, symlink, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { harness } from "./lib/harness.mjs";
import { dissectionNoteRel, DISSECT_NOTE_MAX_BYTES } from "../src/lib/dissect/rules";
import { matchPlotNotes } from "../src/lib/dissect/notes";
import { createNoteDraft } from "../src/lib/dissect/noteDraftCore";
const require = createRequire(import.meta.url);
const { createDissectNotesFamily } = require("../electron/ipc/dissectNotes.cjs");
const { createFileCore } = require("../electron/ipc/files.cjs");
const h = harness("verify-plot-notes");
const scratch = await mkdtemp(path.join(tmpdir(), "flux-plot-notes-"));
const root = path.join(scratch, "project");
await mkdir(path.join(root,"plots"),{recursive:true});
let currentRoot: string|null = root;
const e = { sender: { id: 7 } };
const core = createFileCore({ app:{ getPath:()=>scratch }, dialog:{}, roots:()=>[scratch], setPendingRoot:()=>{}, projectRootFor:()=>currentRoot });
const family = createDissectNotesFamily({ rootFor:()=>currentRoot, atomicWrite:core.atomicWriteMain });
const request = { root, key:"experiment/alpha",group:"",name:"notes.txt",text:"First\n#TODO compare two days\n",expected:null as string|null };
const dest = path.join(root,dissectionNoteRel(request.key,"",request.name));
async function refuses(fn:()=>unknown,label:string) { try { await fn(); h.fail(label); } catch { h.ok(true,label); } }
try {
  h.section("portable names and confinement");
  h.eq(dissectionNoteRel("study/alpha","_stats","results.txt"),"plots/_dissections/study/alpha/_stats/results.txt","owner/group naming follows the dissection convention");
  for(const name of ["../source.svg","note.svg","CON.txt","two/notes.txt","bad\\note.txt","notes.txt ",".txt/other","bad\0.txt"]) await refuses(()=>dissectionNoteRel("alpha","",name),`reject invalid note filename ${JSON.stringify(name)}`);
  for(const key of ["../alpha","alpha/../beta","/absolute","a//b"]) await refuses(()=>dissectionNoteRel(key,"","notes.txt"),`reject invalid owner ${key}`);
  await family.save(e,request);
  h.eq(await readFile(dest,"utf8"),request.text,"creates an ordinary durable text companion");
  await refuses(()=>family.save(e,request),"creating an existing note never replaces it");
  await family.save(e,{...request,expected:request.text,text:"Edited β-cell\n#TODO rerun\n"});
  h.eq(await readFile(dest,"utf8"),"Edited β-cell\n#TODO rerun\n","saved UTF-8 text survives a disk reread");
  await refuses(()=>family.save(e,{...request,text:"stale",expected:request.text}),"stale edit refuses to overwrite external/current content");
  await refuses(()=>family.save(e,{...request,name:"large.txt",text:"x".repeat(DISSECT_NOTE_MAX_BYTES+1)}),"oversized notes are refused before persistence");
  currentRoot=path.join(scratch,"different");
  await refuses(()=>family.save(e,{...request,name:"wrong.txt"}),"a switched project cannot accept an old note write");
  currentRoot=root;
  const source=path.join(root,"plots","source.svg"); await writeFile(source,"SOURCE BYTES");
  const linked=path.join(root,"plots/_dissections/experiment/alpha/linked.txt"); await symlink(source,linked);
  await refuses(()=>family.save(e,{...request,name:"linked.txt",expected:"SOURCE BYTES",text:"changed"}),"a .txt symlink cannot overwrite a source plot");
  h.eq(await readFile(source,"utf8"),"SOURCE BYTES","source bytes remain unchanged after refused symlink write");
  await symlink(path.join(root,"plots"),path.join(root,"plots/_dissections/redirect"));
  await refuses(()=>family.save(e,{...request,key:"redirect",name:"new.txt"}),"a symlinked owner folder cannot escape the note tree");
  const baseline=await readFile(dest,"utf8");
  const results=await Promise.allSettled([family.save(e,{...request,expected:baseline,text:"writer one"}),family.save(e,{...request,expected:baseline,text:"writer two"})]);
  h.eq(results.filter(r=>r.status==="fulfilled").length,1,"two windows editing one baseline serialize; only one may publish");
  const raced=createDissectNotesFamily({rootFor:()=>root,atomicWrite:async(...args:any[])=>{await writeFile(dest,"external write");return core.atomicWriteMain(...args);}});
  const raceBaseline = await readFile(dest,"utf8");
  await refuses(()=>raced.save(e,{...request,expected:raceBaseline,text:"would clobber"}),"publication rechecks the baseline after staging");
  h.eq(await readFile(dest,"utf8"),"external write","the concurrent external writer's bytes survive");
  h.section("project-wide note content matching");
  const matches=matchPlotNotes([{root,key:"a",group:"",name:"notes.txt",path:"a/notes.txt",plot:"a.svg",text:"first\n#TODO Compare spines\nlast"},{root,key:"b",group:"_stats",name:"checks.txt",path:"b/checks.txt",plot:"b.svg",text:"#todo validate"}],"#TODO");
  h.eq(matches.map(n=>[n.key,n.line,n.snippet]),[["a",2,"#TODO Compare spines"],["b",1,"#todo validate"]],"literal case-insensitive tags match across owners and groups with correct line/snippet");
  h.eq(matchPlotNotes(matches,"not-present").length,0,"unmatched note text does not produce a false owner hit");
  h.section("serialized draft drain");
  let releaseWrite!: () => void;
  const barrier = new Promise<void>(resolve => releaseWrite = resolve);
  let saved = "baseline", first = true;
  const draft = createNoteDraft(saved, async (text, expected) => {
    if (first) { first = false; await barrier; }
    if (expected !== saved) throw new Error("stale baseline");
    saved = text;
  });
  draft.edit("first write"); const firstFlush = draft.flush();
  await Promise.resolve(); draft.edit("newest text typed during IO");
  const closingFlush = draft.flush(); releaseWrite();
  await Promise.all([firstFlush, closingFlush]);
  h.eq(saved,"newest text typed during IO","a close-time flush drains edits made while a previous save was in flight");
  h.ok(!draft.current().pending && draft.current().text === draft.current().saved,"the final draft is clean only after the newest text reaches persistence");
  const conflicting = createNoteDraft("old",async()=>{throw new Error("changed externally");});
  conflicting.edit("kept draft"); await refuses(()=>conflicting.flush(),"a conflicting draft flush rejects instead of claiming success");
  h.eq(conflicting.current().text,"kept draft","a failed drain keeps the newest text for recovery");
  h.section("exclusive restore drains newer edits");
  const reentrantWrites: string[] = [];
  const reentrant = createNoteDraft("baseline", async text => { reentrantWrites.push(text); await Promise.resolve(); });
  let joined: Promise<void> | undefined, requestOnce = true;
  const stopObserver = reentrant.subscribe(st => {
    if (st.pending && requestOnce) { requestOnce = false; joined = reentrant.flush(); }
  });
  reentrant.edit("one serialized write");
  await reentrant.flush(); await joined; stopObserver();
  h.eq(reentrantWrites,["one serialized write"],"a synchronous pending observer joins the installed writer instead of starting another");
  let releaseRestore!: () => void;
  const restoreBarrier = new Promise<void>(resolve => releaseRestore = resolve);
  let restoredDisk: string | null = null;
  const expectedWrites: (string | null)[] = [];
  const restored = createNoteDraft("deleted baseline", async(text, expected) => {
    expectedWrites.push(expected);
    if (expected === null) await restoreBarrier;
    if (restoredDisk !== expected) throw new Error("restore baseline changed");
    restoredDisk = text;
  });
  restored.edit("restore snapshot"); const restoring = restored.restore();
  h.ok(restored.current().pending,"exclusive restore registers pending work synchronously");
  restored.edit("newer typing while restoring"); const closeDuringRestore = restored.flush();
  releaseRestore(); await Promise.all([restoring, closeDuringRestore]);
  h.eq(restoredDisk,"newer typing while restoring","held restore followed by close persists the latest text without disabling typing");
  h.eq(expectedWrites,[null,"restore snapshot"],"restore uses exclusive creation once, then exact-baseline replacement for the newer draft");
  h.ok(!restored.current().pending && restored.current().text === restored.current().saved,"restoration becomes clean only after trailing edits are persisted");
  let rejectRestore!: () => void;
  const rejectBarrier = new Promise<void>(resolve => rejectRestore = resolve);
  let winner: string | null = null;
  const failedRestore = createNoteDraft("missing baseline",async(text,expected)=>{
    await rejectBarrier;
    if (winner !== expected) throw new Error("external file reappeared");
    winner = text;
  });
  failedRestore.edit("first restore draft");const restoreFailure=failedRestore.restore();
  failedRestore.edit("newest retained draft");const failedClose=failedRestore.flush();
  const failures=Promise.allSettled([restoreFailure,failedClose]);
  winner="external winner";rejectRestore();
  h.ok((await failures).every(r=>r.status==="rejected"),"a reappearing external file blocks both restore and close-time flush");
  h.eq(winner,"external winner","a failed exclusive restore preserves external bytes");
  h.eq(failedRestore.current().text,"newest retained draft","newer typing survives restore failure for recovery");
} finally { await rm(scratch,{recursive:true,force:true}); }
await h.done();
