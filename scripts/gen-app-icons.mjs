// Regenerate ALL logo artifacts from the phyllotaxis mark (2026-07 redesign):
//   brand/flux-mark-phyllotaxis.svg   — the canonical mark (transparent bg)
//   build/icons/*.png                 — Linux/Windows-Store app icons (dark plate)
//   build/icons/icon.ico              — Windows (PNG-compressed entries)
//   build/icons/icon.icns             — macOS (PNG-typed entries)
//   build/icons/icon.png              — generic 512px
//
// The dot formula is the SAME as src/shell/Logomark.svelte `logoDots()` —
// change one, change both (the constants below are the contract: N=88,
// GOLDEN=137.508, r=4.15√i, dot=1.35+0.036i, hue by radius through the wheel).
//
// Run: node scripts/gen-app-icons.mjs
import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { Resvg } from "@resvg/resvg-js";

const root = join(fileURLToPath(import.meta.url), "..", "..");

const WHEEL = ["#d14d41", "#da702c", "#d0a215", "#35ab49", "#3aa99f", "#4385be", "#8b7ec8", "#ce5d97"];
const GOLDEN = 137.508;
const N = 88;

function logoDots() {
  const dots = [];
  for (let i = 1; i <= N; i++) {
    const a = (i * GOLDEN * Math.PI) / 180;
    const r = 4.15 * Math.sqrt(i);
    dots.push({
      x: +(50 + r * Math.cos(a)).toFixed(2),
      y: +(50 + r * Math.sin(a)).toFixed(2),
      r: +(1.35 + i * 0.036).toFixed(2),
      fill: WHEEL[Math.min(7, Math.floor((r / 39.5) * 8))],
    });
  }
  return dots;
}

const circles = logoDots()
  .map((d) => `  <circle cx="${d.x}" cy="${d.y}" r="${d.r}" fill="${d.fill}"/>`)
  .join("\n");

// 1) The canonical mark — transparent background, the component's geometry verbatim.
const markSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">
<!-- The Flux mark: phyllotaxis bloom (Flexoki accent wheel, hue by radius).
     Generated by scripts/gen-app-icons.mjs — edit the generator, not this file.
     Runtime twin: src/shell/Logomark.svelte. -->
${circles}
</svg>
`;
writeFileSync(join(root, "brand", "flux-mark-phyllotaxis.svg"), markSvg);

// 2) The app-icon plate: dark rounded square, mark centred at 82% width.
const iconSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">
<rect width="100" height="100" rx="21" fill="#100f0f"/>
<g transform="translate(50 50) scale(0.82) translate(-50 -50)">
${circles}
</g>
</svg>
`;

const iconsDir = join(root, "build", "icons");
mkdirSync(iconsDir, { recursive: true });

function renderPng(size) {
  return new Resvg(iconSvg, { fitTo: { mode: "width", value: size } }).render().asPng();
}

// Linux + generic + Windows-Store PNGs (the existing electron-builder file set).
const PNGS = {
  "32x32.png": 32,
  "64x64.png": 64,
  "128x128.png": 128,
  "128x128@2x.png": 256,
  "icon.png": 512,
  "StoreLogo.png": 50,
  "Square30x30Logo.png": 30,
  "Square44x44Logo.png": 44,
  "Square71x71Logo.png": 71,
  "Square89x89Logo.png": 89,
  "Square107x107Logo.png": 107,
  "Square142x142Logo.png": 142,
  "Square150x150Logo.png": 150,
  "Square284x284Logo.png": 284,
  "Square310x310Logo.png": 310,
};
const rendered = new Map();
const png = (size) => {
  if (!rendered.has(size)) rendered.set(size, renderPng(size));
  return rendered.get(size);
};
for (const [name, size] of Object.entries(PNGS)) writeFileSync(join(iconsDir, name), png(size));

// 3) icon.ico — ICO container with PNG-compressed images (Vista+).
function buildIco(sizes) {
  const images = sizes.map((s) => ({ s, data: png(s) }));
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(images.length, 4);
  const dir = Buffer.alloc(16 * images.length);
  let offset = 6 + dir.length;
  images.forEach((img, i) => {
    const o = i * 16;
    dir.writeUInt8(img.s >= 256 ? 0 : img.s, o); // width (0 = 256)
    dir.writeUInt8(img.s >= 256 ? 0 : img.s, o + 1); // height
    dir.writeUInt8(0, o + 2); // palette
    dir.writeUInt8(0, o + 3); // reserved
    dir.writeUInt16LE(1, o + 4); // planes
    dir.writeUInt16LE(32, o + 6); // bpp
    dir.writeUInt32LE(img.data.length, o + 8);
    dir.writeUInt32LE(offset, o + 12);
    offset += img.data.length;
  });
  return Buffer.concat([header, dir, ...images.map((i) => i.data)]);
}
writeFileSync(join(iconsDir, "icon.ico"), buildIco([16, 24, 32, 48, 64, 128, 256]));

// 4) icon.icns — PNG-typed entries only (supported since 10.7).
function buildIcns(entries) {
  const chunks = entries.map(([type, size]) => {
    const data = png(size);
    const head = Buffer.alloc(8);
    head.write(type, 0, "ascii");
    head.writeUInt32BE(8 + data.length, 4);
    return Buffer.concat([head, data]);
  });
  const body = Buffer.concat(chunks);
  const head = Buffer.alloc(8);
  head.write("icns", 0, "ascii");
  head.writeUInt32BE(8 + body.length, 4);
  return Buffer.concat([head, body]);
}
writeFileSync(
  join(iconsDir, "icon.icns"),
  buildIcns([
    ["ic11", 32], // 16pt @2x
    ["ic12", 64], // 32pt @2x
    ["ic07", 128],
    ["ic13", 256], // 128pt @2x
    ["ic08", 256],
    ["ic14", 512], // 256pt @2x
    ["ic09", 512],
    ["ic10", 1024],
  ]),
);

console.log("app icons regenerated from the phyllotaxis mark");
