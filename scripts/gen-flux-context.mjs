#!/usr/bin/env node
// Regenerates electron/fluxContextDocs.gen.cjs from resources/flux-context/*.md.
// The stock FluxContext docs ship as an embedded module (the Guidelines-seed
// idiom: zero packaging changes — the packaged app and the esbuild CLI/MCP
// bundles carry them automatically). The .md files are the SOURCE; the .gen.cjs
// is checked in and drift-gated by scripts/verify-context-scheme.ts.
//
//   node scripts/gen-flux-context.mjs
import * as fs from "node:fs";
import * as path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = path.join(repoRoot, "resources", "flux-context");
const outPath = path.join(repoRoot, "electron", "fluxContextDocs.gen.cjs");

const names = fs
  .readdirSync(srcDir)
  .filter((n) => n.endsWith(".md"))
  .sort();
if (names.length === 0) throw new Error(`no .md files in ${srcDir}`);

const files = {};
const hasher = createHash("sha256");
for (const n of names) {
  const body = fs.readFileSync(path.join(srcDir, n), "utf8");
  files[n] = body;
  hasher.update(n).update("\0").update(body).update("\0");
}
const hash = hasher.digest("hex").slice(0, 16);

// JSON-encode bodies; defensively escape any exact quoted "Flux" token so the
// generated file can never trip verify-fluxconfig's capital-F source scan
// (F === "F"; the parsed content is byte-identical).
const enc = (s) => JSON.stringify(s).replace(/(["'`])Flux(["'`])/g, "$1\\u0046lux$2");

const lines = [
  "// GENERATED by scripts/gen-flux-context.mjs from resources/flux-context/ — DO NOT EDIT.",
  "// Drift-gated by scripts/verify-context-scheme.ts.",
  '"use strict";',
  "module.exports = {",
  `  FLUX_CONTEXT_HASH: ${JSON.stringify(hash)},`,
  "  FLUX_CONTEXT_FILES: {",
  ...names.map((n) => `    ${JSON.stringify(n)}: ${enc(files[n])},`),
  "  },",
  "};",
  "",
];
fs.writeFileSync(outPath, lines.join("\n"));
console.log(`wrote ${path.relative(repoRoot, outPath)} (${names.length} files, hash ${hash})`);
