import { Ajv } from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { readFile, writeFile, unlink } from 'node:fs/promises';
const schema=JSON.parse(await readFile(new URL('./fixtures/model3d/fluxplot/scene3d.schema.json',import.meta.url),'utf8'));
const ajv=new Ajv({strict:false,strictNumbers:true,unicode:false,allErrors:true,code:{source:true,esm:true}});ajv.addSchema(schema,'scene3d');
const text='// GENERATED by scripts/gen-model3d-validator.mjs; do not edit.\n/* eslint-disable */\n'+standaloneCode(ajv,{validateScene3d:'scene3d'})+'\n';
const out=new URL('../src/lib/model3d/scene3dValidator.gen.mjs',import.meta.url);
if(process.argv.includes('--check')){if(await readFile(out,'utf8').catch(()=>null)!==text)throw new Error('scene3d validator is stale');console.log('scene3d validator is fresh');}else await writeFile(out,text);

if(!process.argv.includes('--check')) await unlink(new URL('../src/lib/model3d/scene3dValidator.gen.js',import.meta.url)).catch(()=>{});
