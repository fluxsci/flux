    let scale = 1;
    const opts = { theme: api.FLUX_LIGHT, model3d: host, modelAsset: (id: string) => (fixtures as any)[id]?.asset, modelManifest: (id: string) => (fixtures as any)[id]?.manifest, pixelScale: () => scale, reducedMotion: false };
    const stage = document.getElementById('stage')!, player = api.createPlayer(stage, deck, opts); await player.readyMedia();
