    const host = api.createInlineHost({ sourceKey: 'slide-player-gate', modelBytes: bytes });
    const deck = api.createDeck({ withTitleSlide: false }); deck.stage = { width: 680, height: 340 }; deck.assets = Object.values(fixtures).map((f: any) => f.asset);
    const slide = api.addSlide(deck), f = (fixtures as any).continuous;
    const element = { ...api.makeModel3dElement(f.asset, { id: 'surface', manifest: f.manifest }), x: 20, y: 20, width: 310, height: 290, orbitAzimuth: 30, modelLighting: 'unlit' };
    const shape = { ...api.makeModel3dElement((fixtures as any).states.asset, { id: 'shape' }), x: 360, y: 20, width: 270, height: 270 };
    slide.elements.push(element, shape);
    const beat = api.addBeat(deck, slide.id);
    api.setTransform(deck, slide.id, beat.id, element.id, { state: { orbitAzimuth: -330, orbitZoom: 2, fields: { 'height.field': { range: [0, 2] } } }, duration: 1000, easing: 'linear' });
