#!/usr/bin/env node
// Bundle fluxplot's colour definitions for the app (2026-09-16).
//
//   node scripts/gen-color-collections.mjs            (reads ~/fluxplot)
//   FLUXPLOT_DIR=/path/to/fluxplot node scripts/gen-color-collections.mjs
//
// fluxplot is the ONE source of truth for colormaps and palettes
// (src/fluxplot/definitions/{colormaps,palettes}.json — built there from the
// upstream packages, never imported at runtime). This script writes
// src/lib/color/collections.gen.ts, which is CHECKED IN so the app, its gates and
// the CLI never need the Python checkout: continuous maps keep 32 evenly spaced
// stops (a preview bar and a colour-at-position pick need no more; fluxplot
// applies the full map when a plot regenerates), discrete maps and palettes are
// copied whole. Re-run whenever fluxplot's definitions change.
import { readFileSync, writeFileSync } from "node:fs";
import * as path from "node:path";
import { homedir } from "node:os";
import { fileURLToPath } from "node:url";

const dir = process.env.FLUXPLOT_DIR ?? path.join(homedir(), "fluxplot");
const defs = path.join(dir, "src", "fluxplot", "definitions");
const cmaps = JSON.parse(readFileSync(path.join(defs, "colormaps.json"), "utf8"));
const pals = JSON.parse(readFileSync(path.join(defs, "palettes.json"), "utf8"));
const STOPS = 32;

const sample = (colors, n) => (colors.length <= n ? colors : Array.from({ length: n }, (_, i) => colors[Math.round((i * (colors.length - 1)) / (n - 1))]));

const collections = cmaps.collections.map((c) => ({
  id: c.id,
  name: c.name,
  description: c.description,
  url: c.url,
  license: c.license,
  maps: c.maps.map((m) => ({
    name: m.name,
    type: m.type,
    ...(m.family ? { family: m.family } : {}),
    ...(m.discrete ? { discrete: true } : {}),
    colors: m.discrete ? m.colors : sample(m.colors, STOPS),
  })),
}));
const palettes = pals.collections.map((c) => ({
  id: c.id,
  name: c.name,
  description: c.description,
  url: c.url,
  license: c.license,
  groups: c.groups.map((g) => ({ name: g.name, type: g.type, swatches: g.swatches.map((s) => ({ name: s.name, hex: s.hex })) })),
}));

const header = `// GENERATED by scripts/gen-color-collections.mjs from fluxplot's definitions
// (${cmaps.schema}, ${pals.schema}) — do not edit; re-run the script when fluxplot's
// definitions/*.json change. Continuous maps carry ${STOPS} stops (previews and
// colour-at-position picks); fluxplot applies the full map when a plot regenerates.
`;
const pure = `${header}
export type ColormapType = "sequential" | "diverging" | "cyclic" | "qualitative" | "misc";

export interface ColormapDef {
  /** Bare name inside its collection; the qualified name is \`\${collection}.\${name}\`. */
  name: string;
  type: ColormapType;
  family?: string;
  /** Exact colour list (a categorical map) rather than sampled stops. */
  discrete?: true;
  colors: string[];
}
export interface ColormapData {
  id: string;
  maps: ColormapDef[];
}
export const COLORMAP_DATA: ColormapData[] = ${JSON.stringify(collections.map(({id,maps})=>({id,maps})))};
`;
const out = `${header}
import type { ColorGroup } from "../types";
import { COLORMAP_DATA, type ColormapData } from "./colormaps.gen";
export type { ColormapDef, ColormapType } from "./colormaps.gen";
export interface ColormapCollection extends ColormapData {
  name: string;
  description: string;
  url: string;
  license: string;
}
export interface PaletteGroup extends ColorGroup {
  type: string;
}
export interface PaletteCollection {
  id: string;
  name: string;
  description: string;
  url: string;
  license: string;
  groups: PaletteGroup[];
}

const COLORMAP_METADATA = ${JSON.stringify(collections.map(({maps,...metadata})=>metadata))};
export const COLORMAP_COLLECTIONS: ColormapCollection[] = COLORMAP_METADATA.map((meta, i) => ({ ...meta, maps: COLORMAP_DATA[i].maps }));

export const PALETTE_COLLECTIONS: PaletteCollection[] = ${JSON.stringify(palettes)};
`;
// The FULL lookup tables (colour-system plan A7.2): fluxplot stores 256 samples per continuous
// map = the exact table of an N=256 map, so a live colour-scale edit that names a map paints
// with matplotlib's own entries. Packed as one string of 6 hex digits per entry (no quotes, no
// commas) in its OWN module, imported lazily by color/colormapLuts.ts — never from the eager
// bundle (verify-startup's budget) nor from the offline deck runtime.
const luts = {};
for (const c of cmaps.collections) for (const m of c.maps) luts[`${c.id}.${m.name}`] = m.colors.map((h) => h.slice(1)).join("");
const lutModule = `${header}
// Every map's full table (${cmaps.samples} entries per continuous map; a discrete map its exact
// colours), packed as 6 hex digits per entry. Read through color/colormapLuts.ts (lazy import).
export const COLORMAP_LUTS: Record<string, string> = ${JSON.stringify(luts)};
`;
const folder = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "color");
const target = path.join(folder, "collections.gen.ts");
// The LUT module needs fluxplot's full 256-sample tables; definitions carrying only preview
// stops (verify-color-collections' round-trip scratch is built from the 32-stop bundle) can
// neither reproduce nor replace it, so it is left alone with a note.
const fullTables = Number(cmaps.samples) >= 256;
const outputs = [[target,out],[path.join(folder,"colormaps.gen.ts"),pure]];
if (fullTables) outputs.push([path.join(folder,"colormapLuts.gen.ts"),lutModule]);
else console.log("colormapLuts.gen.ts untouched: these definitions carry preview stops, not full tables");
for (const [file, text] of outputs) {
  if (process.argv.includes('--check')) { if (readFileSync(file,'utf8') !== text) throw new Error(`Stale generated colours: ${file}`); }
  else writeFileSync(file,text);
}
console.log(`wrote ${path.relative(process.cwd(), target)}: ${collections.map((c) => `${c.id} ${c.maps.length} maps`).join(", ")}; palettes ${palettes.map((c) => `${c.id} ${c.groups.length} groups`).join(", ")} (${(out.length / 1024).toFixed(0)} KB)`);
