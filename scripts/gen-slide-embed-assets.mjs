// Build-owned runtime + CSP hash. Never edit the emitted files by hand.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({ absWorkingDir: root, entryPoints: ['src/lib/slide/embedDocumentRuntime.ts'], bundle: true, write: false, format: 'iife', target: 'es2022', minify: true, define: { 'import.meta.env.DEV': 'false' } });
const runtime = result.outputFiles[0].text;
const csp = `'sha256-${createHash('sha256').update(runtime).digest('base64')}'`;
const faces = await Promise.all(['Gelasio', 'Gelasio-italic'].map(async name => `@font-face{font-family:Gelasio;font-style:${name.endsWith('italic') ? 'italic' : 'normal'};font-weight:400 700;src:url(data:font/woff2;base64,${(await readFile(`${root}/src/styles/fonts/${name}.woff2`)).toString('base64')}) format('woff2')}`));
await mkdir(`${root}/.generated`, { recursive: true });
for (const [file, text] of [[`${root}/.generated/slide-embed-assets.json`, JSON.stringify({ runtime, csp, fonts: faces.join('\n') })], [`${root}/electron/slideEmbedCsp.gen.cjs`, `// Generated by scripts/gen-slide-embed-assets.mjs\nmodule.exports = ${JSON.stringify(csp)};\n`]]) {
  if (await readFile(file, 'utf8').catch(() => '') !== text) await writeFile(file, text);
}
console.log(`Slide embed runtime: ${Math.round(runtime.length / 1024)} KB`);
