// Build the "Add to FluxLib" browser extension into extension/dist/.
//
// The only real job here is keeping ONE source of truth. The extension needs the same
// supplement URL patterns and the same capture-filename contract that Flux itself uses
// (electron/captureRules.js, electron/supplementRules.js) — and a hand-copied second set is
// exactly how the supplement filter rotted the first time. So those files are COPIED at build
// time into extension/dist/vendor/ and re-exported as one module, never edited by hand.
//
// Run:  node scripts/build-extension.mjs      (or npm run build:extension)
// Sign: npm run sign:extension                 → extension/signed/*.xpi, for Firefox
//
// Flux's Library → Web capture → Set up… installs from these outputs; by hand it's
// chrome://extensions → Developer mode → Load unpacked → extension/dist (Chromium), or
// opening the signed .xpi (Firefox).
import { readFile, writeFile, mkdir, rm, cp } from "node:fs/promises";
import { existsSync } from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "extension");
const out = path.join(src, "dist");

await rm(out, { recursive: true, force: true });
await mkdir(path.join(out, "vendor"), { recursive: true });
await mkdir(path.join(out, "icons"), { recursive: true });

// --- shared rules, copied not duplicated -------------------------------------------------
for (const f of ["captureRules.js", "supplementRules.js"]) {
  await cp(path.join(root, "electron", f), path.join(out, "vendor", f));
}
// One import surface for the worker, so background.js never reaches into Flux's tree layout.
await writeFile(
  path.join(out, "vendor", "captureShared.js"),
  `// GENERATED by scripts/build-extension.mjs — do not edit.
// Re-exports the SHARED rules copied verbatim from Flux's electron/ tree, so the extension,
// the Flux watcher and the bookmarklet can never disagree about what a capture file is.
export { SUPPLEMENT_URL_PATTERNS } from "./supplementRules.js";
export { captureSlug, SUPP_PREFIX, SUPP_SEP, CAPTURE_PREFIX, CAPTURE_EXT, CAPTURE_SUBDIR } from "./captureRules.js";
// The NAME BUILDERS and the recognizer. The worker must not assemble a capture filename itself:
// sanitizing an assembled name strips the \`@@\` separator back out, which silently cost every
// captured supplement. isCaptureFile lets the worker refuse a name Flux would never see.
export { isCaptureFile, safeCaptureFileName, articleCaptureName, sidecarCaptureName, supplementCaptureName } from "./captureRules.js";
`,
);

// --- sources -----------------------------------------------------------------------------
for (const f of ["background.js", "page.js"]) await cp(path.join(src, f), path.join(out, f));

// --- icons: reuse the app's, so the toolbar button IS the Flux mark ----------------------
const iconSrc = path.join(root, "build", "icons");
// build/icons only ships a few sizes; map each manifest slot to the nearest available.
for (const [size, file] of [
  [16, "32x32.png"],
  [32, "32x32.png"],
  [48, "64x64.png"],
  [128, "128x128.png"],
]) {
  const from = existsSync(path.join(iconSrc, file)) ? path.join(iconSrc, file) : path.join(iconSrc, "32x32.png");
  await cp(from, path.join(out, "icons", `${size}.png`));
}

// --- manifest: keep Chrome and Firefox both happy ----------------------------------------
// The version comes from the SOURCE manifest and is NOT derived from package.json. AMO refuses
// a version it has already seen, so the extension needs its own monotonic line that
// sign-extension.mjs bumps — deriving it from the app version silently discarded that bump and
// would have made every signing run after the first fail on a duplicate version.
const manifest = JSON.parse(await readFile(path.join(src, "manifest.json"), "utf8"));
if (!/^\d+(\.\d+){0,3}$/.test(String(manifest.version || ""))) {
  console.error(`✗ extension/manifest.json has an invalid version: ${manifest.version}`);
  process.exit(1);
}
// MV3 background differs by engine: Chrome wants `service_worker`, Firefox wants `scripts`.
// Keeping BOTH keys is valid — each browser reads the one it understands and ignores the other.
await writeFile(path.join(out, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

console.log(`✓ extension built → ${path.relative(root, out)}  (v${manifest.version})`);
console.log("  Chromium: chrome://extensions → Developer mode → Load unpacked → this folder");
console.log("  Firefox : npm run sign:extension, then open extension/signed/*.xpi");
