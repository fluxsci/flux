#!/usr/bin/env node
// Vendor fluxplot's manifest and recipe JSON Schemas into src/lib/plot/schemas/ and record the
// fluxplot commit they came from, then regenerate src/lib/plot/types.gen.ts from them (F3 of the
// colour-system plan). fluxplot's schema is the ONE contract: Flux validates incoming plots with
// the vendored copy and its TypeScript types derive from it, so the two repos cannot drift
// silently — verify-fluxplot-schema.ts pins that the generated types match the vendored schema.
//
//   node scripts/sync-fluxplot-schemas.mjs [--fluxplot <path>]      (default ../fluxplot, then ~/fluxplot)
//   node scripts/sync-fluxplot-schemas.mjs --types-only              (regenerate types.gen.ts from the vendored copy)
import { execFileSync } from "node:child_process";
import { promises as fs } from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
export const OUT_DIR = path.join(root, "src", "lib", "plot", "schemas");
export const TYPES_OUT = path.join(root, "src", "lib", "plot", "types.gen.ts");
const FILES = ["manifest.schema.json", "recipe.schema.json"];

function fluxplotDir(argv) {
  const i = argv.indexOf("--fluxplot");
  if (i >= 0) return path.resolve(argv[i + 1]);
  for (const cand of [path.resolve(root, "..", "fluxplot"), path.join(os.homedir(), "fluxplot")]) {
    try { execFileSync("git", ["-C", cand, "rev-parse", "HEAD"], { stdio: "pipe" }); return cand; } catch { /* next */ }
  }
  throw new Error("fluxplot checkout not found; pass --fluxplot <path>");
}

export async function vendor(dir) {
  const commit = execFileSync("git", ["-C", dir, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
  const dirty = execFileSync("git", ["-C", dir, "status", "--porcelain", "--", "src/fluxplot/schemas"], { encoding: "utf8" }).trim().length > 0;
  await fs.mkdir(OUT_DIR, { recursive: true });
  for (const f of FILES) {
    const text = await fs.readFile(path.join(dir, "src", "fluxplot", "schemas", f), "utf8");
    await fs.writeFile(path.join(OUT_DIR, f), text);
  }
  const manifest = JSON.parse(await fs.readFile(path.join(OUT_DIR, "manifest.schema.json"), "utf8"));
  const source = { fluxplotCommit: commit, schemasDirty: dirty, manifestId: manifest.$id, syncedAt: new Date().toISOString().slice(0, 10) };
  await fs.writeFile(path.join(OUT_DIR, "SOURCE.json"), JSON.stringify(source, null, 2) + "\n");
  return source;
}

/** The generated TypeScript for the vendored schemas (pure: no file writes). */
export async function generateTypes() {
  const { compile } = await import("json-schema-to-typescript");
  const banner = "// GENERATED by scripts/sync-fluxplot-schemas.mjs from src/lib/plot/schemas/*.schema.json\n" +
    "// (fluxplot's manifest and recipe contract). Do not edit; re-sync from fluxplot instead.\n" +
    "// Drift-gated by scripts/verify-fluxplot-schema.ts.\n/* eslint-disable */";
  const options = { bannerComment: "", additionalProperties: false, strictIndexSignatures: false,
    style: { singleQuote: false, semi: true, printWidth: 110 }, cwd: OUT_DIR, unreachableDefinitions: true };
  const manifest = JSON.parse(await fs.readFile(path.join(OUT_DIR, "manifest.schema.json"), "utf8"));
  const recipe = JSON.parse(await fs.readFile(path.join(OUT_DIR, "recipe.schema.json"), "utf8"));
  // the manifest's `parts` is `allOf: [$ref partNode]` for the extra `required`; json2ts renders that
  // faithfully but verbosely — name the root type FluxPlotManifestGen so types.ts can narrow it.
  const m = await compile({ ...manifest, title: "FluxPlotManifestGen" }, "FluxPlotManifestGen", options);
  const r = await compile({ ...recipe, title: "FluxPlotRecipeGen" }, "FluxPlotRecipeGen", options);
  return `${banner}\n\n${m.replace(/^\/\*[\s\S]*?\*\/\s*/, "")}\n${r.replace(/^\/\*[\s\S]*?\*\/\s*/, "")}`;
}

const argv = process.argv.slice(2);
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (!argv.includes("--types-only")) {
    const source = await vendor(fluxplotDir(argv));
    console.log(`vendored ${FILES.join(", ")} from fluxplot ${source.fluxplotCommit.slice(0, 8)}${source.schemasDirty ? " (schemas dirty!)" : ""}`);
  }
  const types = await generateTypes();
  await fs.writeFile(TYPES_OUT, types);
  console.log(`wrote ${path.relative(root, TYPES_OUT)} (${types.split("\n").length} lines)`);
}
